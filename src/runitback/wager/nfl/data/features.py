OPP_STATS_COLUMNS = [f"opp_{col}" for col in STATS_COLUMNS]

# Betting-market columns from the nflverse schedule. Only the next week's games
# carry lines, and using them makes a model echo the market, so they are not
# default features; pass them as `context` to opt in.
MARKET_COLUMNS = [
    "spread_line",
    "total_line",
    "moneyline",
    "opp_moneyline",
    "over_odds",
    "under_odds",
]

SCHEMA = GameSchema(
    season="season",
    date="week",
    team="team",
    opp="opp_team",
    game_id="game_id",
    target="result",
    stats=tuple(STATS_COLUMNS + OPP_STATS_COLUMNS + ["score", "opp_score"]),
    location="location",
    # injury features close ~22% of the transformer's Brier gap to Vegas on
    # 2021-2025 (-0.0028 +/- 0.0025), most of it in games with a new QB
    context=("rest", "opp_rest", "div_game", *INJURY_COLUMNS, *OPP_INJURY_COLUMNS),
    categorical=("game_type", "roof", "surface"),
    paired=(
        ("score", "opp_score"),
        ("rest", "opp_rest"),
        ("moneyline", "opp_moneyline"),
        ("spread_odds", "opp_spread_odds"),
        ("qb_id", "opp_qb_id"),
        ("qb_name", "opp_qb_name"),
        ("coach", "opp_coach"),
        *zip(INJURY_COLUMNS, OPP_INJURY_COLUMNS),
    ),
    negated=("spread_line",),
    display=("gameday", "gametime", *MARKET_COLUMNS),
    market_spread="spread_line",
    market_moneyline=("moneyline", "opp_moneyline"),
    total="total",
    market_total="total_line",
    market_total_odds=("over_odds", "under_odds"),
)
